// Ported from the owner's linkedlist/LinkedList.java (merge, used by mergeSort), unchanged.
class Solution {
    public ListNode mergeLists(ListNode head1, ListNode head2) {
        ListNode mergedLL = new ListNode(-1);
        ListNode temp = mergedLL;
        while (head1 != null && head2 != null) {
            if (head1.val <= head2.val) {
                temp.next = head1;
                head1 = head1.next;
                temp = temp.next;
            } else {
                temp.next = head2;
                head2 = head2.next;
                temp = temp.next;
            }
        }
        while (head1 != null) {
            temp.next = head1;
            head1 = head1.next;
            temp = temp.next;
        }
        while (head2 != null) {
            temp.next = head2;
            head2 = head2.next;
            temp = temp.next;
        }
        return mergedLL.next;
    }
}
